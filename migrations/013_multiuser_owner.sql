-- 013: multi-user beta, step 1 (P1). Users + an owner on every user table. No behaviour change.
-- Additive only, safe to re-run: one new table, one seed row inserted only if absent, one nullable
-- column per table added only if absent, indexes only if absent, one new read-only function
-- created only if absent. Applied with the Supabase management API by the agent (additive, per
-- CLAUDE.md) before the app code that reads owner_id is deployed.
--
-- Backfill without UPDATE: ADD COLUMN ... DEFAULT 1 fills every existing row with user #1 (Riley,
-- the owner) once, when the column is created. A rerun skips the column (IF NOT EXISTS), so it can
-- never reassign a row. The DEFAULT also covers rows the current production code inserts before
-- this branch is deployed; the new code always sends owner_id itself (invariant
-- "owner-on-insert"). Dropping the default after the deploy is a later migration (P6).

CREATE TABLE IF NOT EXISTS mdshare_users (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 2) PRIMARY KEY,
  created_at         timestamptz NOT NULL DEFAULT now(),
  label              text CHECK (label IS NULL OR length(label) <= 100),
  entry_hash         text UNIQUE,                 -- sha256 of the entry-link secret (P3); never the secret
  disabled           boolean NOT NULL DEFAULT false,
  quota_docs_per_day integer NOT NULL DEFAULT 200,
  quota_bytes        integer NOT NULL DEFAULT 524288
);
ALTER TABLE mdshare_users ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON mdshare_users FROM anon, authenticated;

-- User #1 is the owner. Explicit id (the identity starts at 2, so a generated id never collides).
INSERT INTO mdshare_users (id, label) VALUES (1, 'owner') ON CONFLICT (id) DO NOTHING;

ALTER TABLE mdshare_pastes       ADD COLUMN IF NOT EXISTS owner_id bigint DEFAULT 1 REFERENCES mdshare_users (id);
ALTER TABLE mdshare_diagrams     ADD COLUMN IF NOT EXISTS owner_id bigint DEFAULT 1 REFERENCES mdshare_users (id);
ALTER TABLE mdshare_archify      ADD COLUMN IF NOT EXISTS owner_id bigint DEFAULT 1 REFERENCES mdshare_users (id);
ALTER TABLE mdshare_agent_tokens ADD COLUMN IF NOT EXISTS owner_id bigint DEFAULT 1 REFERENCES mdshare_users (id);
ALTER TABLE mdshare_events       ADD COLUMN IF NOT EXISTS owner_id bigint DEFAULT 1 REFERENCES mdshare_users (id);
ALTER TABLE mdshare_reads        ADD COLUMN IF NOT EXISTS owner_id bigint DEFAULT 1 REFERENCES mdshare_users (id);
ALTER TABLE mdshare_feedback     ADD COLUMN IF NOT EXISTS owner_id bigint DEFAULT 1 REFERENCES mdshare_users (id);

